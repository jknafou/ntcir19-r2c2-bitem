"""Ways of combining accuracy with HMR, drawn as the trade each one makes.

    /usr/bin/python3 analysis/composite_shapes.py

Writes docs/figures/composite-shapes.tex (build with `bash docs/figures/build.sh
composite-shapes`) and the findings to analysis/composite_shapes.md.

The question. HMR says nothing about correctness, so a run can score well while answering badly.
Reporting accuracy alongside it is the obvious repair, and the paper proposes their product. But
`accuracy x HMR` is one choice among several, and each choice rewards something different, so
this draws what each one rewards.

How it is drawn. Accuracy on one axis, HMR on the other, the filed runs as dots, and one contour
for each of two rules through the point (0.5, 0.5): the product, solid, and the harmonic mean,
dashed. A contour shows what a rule rewards, because it is the direction a run must move to keep
the same score. Both contours bend away from the axes, so the closer a run is to being worthless
on one of the two, the more of the other it must give to hold its score.

What the shapes mean. The product and the geometric mean induce the same ordering, since one is a
monotone function of the other, so they share a curve and differ only in the number printed. The
arithmetic mean is a straight line, which is what fully compensatory means: a run can trade any
amount of one for the other. The harmonic mean bends further from the axes than the product, so it
punishes imbalance harder. The minimum is the corner itself, the most conservative reading.

What the figure cannot show. Accuracy does not depend on the filed confidences, so for a fixed set
of answers the confidence that maximises any of these composites is the confidence that maximises
HMR, and HMR is monotone in each confidence, decreasing in the confidence filed on a wrong answer
and increasing on a right one. Its optimum is therefore an endpoint, 0 or 100. HMR is not linear
in a confidence: a single confidence enters exactly one of R_O and R_U, so HMR becomes 2xC/(x+C)
in that reward, which is concave, and the first differences measured over a realistic run range
from -0.0228 to -0.0281. The corner solution follows from monotonicity alone. So none of these
composites repairs HMR's own incentive; they only make the reported number sensitive to
correctness. As a number to read beside a ranking the product is
honest and legible; as a number to optimise it is not.

Read-only over results/.
"""
from __future__ import annotations

import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "results" / "OfficialResults"
TEX = ROOT / "docs" / "figures" / "composite-shapes.tex"
MD = ROOT / "analysis" / "composite_shapes.md"

OURS = ("BITEM-AC-1", "BITEM-AC-2", "BITEM-AC-3", "BITEM-AC-4")

#: name -> (value at (a, h), curve h(a) through (0.5, 0.5))
RULES = {
    "product": (lambda a, h: a * h, lambda a: 0.25 / a),
    "geometric": (lambda a, h: (a * h) ** 0.5, lambda a: 0.25 / a),
    "harmonic": (lambda a, h: 0.0 if a + h == 0 else 2 * a * h / (a + h),
                 lambda a: a / (4 * a - 1) if 4 * a - 1 > 0 else None),
    "arithmetic": (lambda a, h: (a + h) / 2, lambda a: 1 - a),
    "minimum": (lambda a, h: min(a, h), None),
}


def runs():
    """(name, accuracy, HMR) for every AC run the organisers scored."""
    out = []
    with (RES / "official.AC.csv").open(encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            name = r[""].replace(".official", "")
            try:
                out.append((name, float(r["accuracy"]), float(r["HMR"])))
            except (KeyError, ValueError):
                continue
    return sorted(out)


def curve(fn, lo=0.26, hi=1.0, step=0.01):
    pts = []
    a = lo
    while a <= hi + 1e-9:
        h = fn(a)
        if h is not None and 0.0 <= h <= 1.0:
            pts.append((a, h))
        a += step
    return pts


def main() -> int:
    data = runs()

    # Our runs, labelled as the paper names them. AC-4 as filed duplicates AC-3, so it is not
    # drawn twice; the recovered judge run is drawn in its place.
    # Filed runs are solid, runs that were never filed are hollow.
    MINE = [("AC-1", 0.9062, 0.2719, "below", True), ("AC-2", 0.9219, 0.4915, "above", True),
            ("AC-3", 0.8906, 0.3956, "left", True), ("m-a-j", 0.9375, 0.2952, "right", False),
            ("revised 1p", 0.9062, 0.6639, "left", False),
            ("revised 4p", 0.9375, 0.6985, "left", False)]
    AX, AH = 0.9375, 0.6985                       # the anchor, our best rebuilt run
    cp = AX * AH                                  # product level through it
    ch = 2 * AX * AH / (AX + AH)                  # harmonic level through it

    L = ["% Generated by analysis/composite_shapes.py -- do not edit by hand.",
         "% Build:  bash docs/figures/build.sh composite-shapes", "",
         "\\documentclass[tikz,border=2pt]{standalone}",
         "\\usepackage{lmodern}",
         "\\definecolor{prod}{HTML}{1F4E79}",
         "\\definecolor{harm}{HTML}{A63603}",
         "\\definecolor{faint}{HTML}{9AA5B1}",
         "\\begin{document}", "\\begin{tikzpicture}[x=58mm,y=58mm,font=\\scriptsize]",
         "  \\draw[faint] (0,0) rectangle (1,1);",
         "  \\foreach \\v in {0.25,0.5,0.75} {",
         "    \\draw[faint!30] (\\v,0) -- (\\v,1);",
         "    \\draw[faint!30] (0,\\v) -- (1,\\v); }",
         "  \\node[below] at (0.5,-0.06) {accuracy};",
         "  \\node[rotate=90,above] at (-0.07,0.5) {HMR};",
         "  \\foreach \\v in {0,0.5,1} {",
         "    \\node[below,font=\\tiny] at (\\v,0) {\\v};",
         "    \\node[left,font=\\tiny] at (0,\\v) {\\v}; }"]

    mine_at = {(round(a, 4), round(h, 4)) for _, a, h, _, _ in MINE}
    for name, a, h in data:
        if (round(a, 4), round(h, 4)) in mine_at:
            continue
        L.append("  \\node[circle,draw=faint!80,fill=faint!80,inner sep=0.8pt] "
                 "at (%.4f,%.4f) {};" % (a, h))

    def plot(level, fn, col, dash):
        pts, a = [], 0.01
        while a <= 1.0 + 1e-9:
            h = fn(a, level)
            if h is not None and 0 <= h <= 1:
                pts.append((a, h))
            a += 0.004
        if pts:
            L.append("  \\draw[%s,very thick,opacity=0.5,%s] plot coordinates {%s};"
                     % (col, dash, " ".join("(%.4f,%.4f)" % q for q in pts)))

    prod_fn = lambda a, c: c / a
    harm_fn = lambda a, c: (c * a / (2 * a - c)) if 2 * a - c > 1e-9 else None
    # one anchor only, a run at 0.5 on both, so the two shapes are read against each other
    ANCHOR = 0.5
    plot(ANCHOR * ANCHOR, prod_fn, "prod", "solid")
    plot(2 * ANCHOR * ANCHOR / (2 * ANCHOR), harm_fn, "harm", "dashed")
    L.append("  \\node[circle,draw=faint,fill=white,inner sep=1.0pt] at (%.2f,%.2f) {};"
             % (ANCHOR, ANCHOR))

    pos = {"above": "above", "below": "below", "left": "left", "right": "right"}
    for name, a, h, where, filed in MINE:
        fill = "black" if filed else "white"
        L.append("  \\node[circle,draw=black,fill=%s,inner sep=1.0pt] at (%.4f,%.4f) {};"
                 % (fill, a, h))
        L.append("  \\node[%s,font=\\tiny,inner sep=1.6pt] at (%.4f,%.4f) {%s};"
                 % (pos[where], a, h, name))

    y = 0.30                                  # dots first, rules under them
    for lab, draw, fill in (("our filed runs", "black", "black"),
                            ("ours, never filed", "black", "white"),
                            ("other teams", "faint!80", "faint!80")):
        L.append("  \\node[circle,draw=%s,fill=%s,inner sep=0.9pt] at (0.105,%.3f) {};"
                 % (draw, fill, y))
        col = ",faint" if draw.startswith("faint") else ""
        L.append("  \\node[right,font=\\tiny%s] at (0.168,%.3f) {%s};" % (col, y, lab))
        y -= 0.055
    for lab, col, dash in (("accuracy $\\times$ HMR @0.5", "prod", "solid"),
                           ("harmonic mean @0.5", "harm", "dashed")):
        L.append("  \\draw[%s,very thick,opacity=0.5,%s] (0.055,%.3f) -- (0.150,%.3f);"
                 % (col, dash, y, y))
        L.append("  \\node[right,font=\\tiny,%s] at (0.168,%.3f) {%s};" % (col, y, lab))
        y -= 0.055
    L += ["\\end{tikzpicture}", "\\end{document}"]
    TEX.parent.mkdir(parents=True, exist_ok=True)
    TEX.write_text("\n".join(L) + "\n", encoding="utf-8")

    # The write-up
    md = ["# Combining accuracy with HMR: what each rule rewards", "",
          "Produced by `analysis/composite_shapes.py`. The figure is",
          "`docs/figures/composite-shapes.tex`.", "",
          "## 1. The rules, on the cases that separate them", "",
          "| accuracy | HMR | product | geometric | harmonic | arithmetic | minimum |",
          "|---|---|---|---|---|---|---|"]
    cases = [(0.5, 1.0), (1.0, 0.5), (0.9, 0.3), (0.5, 0.5), (1.0, 0.0), (0.0, 1.0), (0.9, 0.9)]
    for a, h in cases:
        md.append("| %.2f | %.2f | %s |" % (a, h, " | ".join(
            "%.4f" % RULES[r][0](a, h) for r in
            ("product", "geometric", "harmonic", "arithmetic", "minimum"))))
    md += ["",
           "The first row is the case the author raised: half the answers right with a perfectly",
           "meaningful confidence. Only the product and the minimum return 0.5 there. The",
           "geometric mean returns 0.7071 and the arithmetic mean 0.75, both of which read as",
           "better than the system is. Row five is the other end, a run that is always right and",
           "tells you nothing about when it is wrong, where the arithmetic mean still awards 0.5.",
           ""]

    md += ["## 2. What each ordering does to the field", "",
           "Every scored AC run, ranked by each rule. A rule that reorders the leaders is a rule",
           "that makes a claim, and that applies to all of them: our accuracy is near the top of the field and our calibration is poor, so",
           "every accuracy-aware rule moves BITEM up.", "",
           "| run | accuracy | HMR | HMR rank | product | geometric | harmonic | arithmetic | minimum |",
           "|---|---|---|---|---|---|---|---|---|"]
    order = {r: {n: i + 1 for i, (n, _, _) in
                 enumerate(sorted(data, key=lambda t: -RULES[r][0](t[1], t[2])))}
             for r in RULES}
    hmr_rank = {n: i + 1 for i, (n, _, _) in enumerate(sorted(data, key=lambda t: -t[2]))}
    for name, a, h in sorted(data, key=lambda t: -t[2]):
        md.append("| %s | %.4f | %.4f | %d | %d | %d | %d | %d | %d |"
                  % (name, a, h, hmr_rank[name], order["product"][name],
                     order["geometric"][name], order["harmonic"][name],
                     order["arithmetic"][name], order["minimum"][name]))
    md += ["",
           "Product and geometric give identical ranks throughout, which is the point made in the",
           "docstring: one is a monotone function of the other, so choosing between them is a",
           "choice of scale and not of ordering.", ""]

    # how far each rule moves the field against HMR alone
    md += ["## 3. How far each rule moves the field", "",
           "| rule | runs moved 2 places or more | largest move | top run |",
           "|---|---|---|---|"]
    for r in ("product", "geometric", "harmonic", "arithmetic", "minimum"):
        moves = [abs(order[r][n] - hmr_rank[n]) for n, _, _ in data]
        top = min(data, key=lambda t: order[r][t[0]])[0]
        md.append("| %s | %d | %d | %s |"
                  % (r, sum(1 for m in moves if m >= 2), max(moves), top))
    import re as _re
    from collections import defaultdict as _dd

    def _pq(f):
        d = _dd(dict)
        for line in f.open(encoding="utf-8"):
            m = _re.match(r"(\d+)\s+(Conf|Correct)=\s*([\d.]+)", line)
            if m:
                d[m.group(1)][m.group(2)] = float(m.group(3))
        return {q: v for q, v in d.items() if "Conf" in v and "Correct" in v}

    worst_l = worst_q = 0.0
    nrun = 0
    for f in sorted((RES / "ACnev").iterdir()):
        d = _pq(f)
        if not d:
            continue
        nrun += 1
        pr = [v["Conf"] / 100 for v in d.values()]
        y = [v["Correct"] for v in d.values()]
        n = len(d)
        acc = sum(y) / n
        neg = [pi for pi, yi in zip(pr, y) if yi == 0]
        pos = [pi for pi, yi in zip(pr, y) if yi == 1]
        R_O = 1.0 if not neg else 1 - sum(neg) / len(neg)
        R_U = 1.0 if not pos else sum(pos) / len(pos)
        S_O = 1.0 if not neg else 1 - sum(pi ** 2 for pi in neg) / len(neg)
        S_U = 1.0 if not pos else 1 - sum((1 - pi) ** 2 for pi in pos) / len(pos)
        mae = sum(abs(pi - yi) for pi, yi in zip(pr, y)) / n
        bs = sum((pi - yi) ** 2 for pi, yi in zip(pr, y)) / n
        worst_l = max(worst_l, abs(((1 - acc) * R_O + acc * R_U) - (1 - mae)))
        worst_q = max(worst_q, abs(((1 - acc) * S_O + acc * S_U) - (1 - bs)))
    md += ["", "## 4. Accuracy as the weight rather than as a factor", "",
           "`R_O` and `R_U` are means over two disjoint groups, the questions a run got wrong and",
           "the ones it got right, and accuracy is how many are in each. HMR takes the harmonic",
           "mean of the two group scores and never uses the group sizes, which is where the",
           "accuracy goes. Weighting them by it instead gives a measure that is already standard:",
           "",
           "| identity | largest error over the %d scored runs |" % nrun,
           "|---|---|",
           "| `(1-a) R_O + a R_U = 1 - MAE` | %.2e |" % worst_l,
           "| `(1-a) S_O + a S_U = 1 - Brier` | %.2e |" % worst_q, "",
           "`S_O` and `S_U` are the same two group means under a squared penalty rather than a",
           "linear one. The Brier form is strictly proper, which is the property no product of",
           "accuracy with HMR can have.", ""]

    md += ["",
           "## 4. The limitation none of this addresses", "",
           "Accuracy is fixed once the answers are fixed, so for a given set of answers the",
           "confidence that maximises any of these composites is the confidence that maximises",
           "HMR, and HMR is monotone in each confidence, so its optimum is an endpoint. Filing 0",
           "or 100 and nothing between is",
           "optimal under all five. They make the reported number sensitive to correctness. None",
           "of them changes what a system is rewarded for doing with its confidences. As a number to read beside a ranking the product is",
           "legible and hard to game by accident. As a number to optimise it is the wrong tool.",
           ""]
    MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
